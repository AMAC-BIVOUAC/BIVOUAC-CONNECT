/** Messages dynamiques venant du processus principal (main.js, ai.js) */
const EN_PATTERNS = [
  [/^Aucune clé API enregistrée pour (.+)\.$/, 'No API key saved for $1.']
];

/** Traduit un texte d'interface. Le français est la clé et la valeur de secours. */
function tr(fr, vars) {
  let s = fr;
  if (B.lang === 'en') {
    if (EN[fr] !== undefined) s = EN[fr];
    else for (const [re, en] of EN_PATTERNS) if (re.test(fr)) { s = fr.replace(re, en); break; }
  }
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

/** Format des dates et heures */
B.locale = () => (B.lang === 'en' ? 'en-GB' : 'fr-FR');

/** Change la langue de CE poste puis recharge l'application (la session reste ouverte) */
B.setLang = (lang) => {
  store.set('lang', lang === 'en' ? 'en' : 'fr');
  location.reload();
};

/** Traduit la partie fixe de index.html (textes, placeholder, title) */
function translateStatic(root) {
  if (B.lang === 'fr') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const key = n.nodeValue.trim();
    if (key && EN[key] !== undefined) n.nodeValue = n.nodeValue.replace(key, EN[key]);
  }
  for (const el of root.querySelectorAll('[placeholder], [title]')) {
    for (const attr of ['placeholder', 'title']) {
      const v = el.getAttribute(attr);
      if (v && EN[v] !== undefined) el.setAttribute(attr, EN[v]);
    }
  }
}
document.documentElement.lang = B.lang;
translateStatic(document.body);
